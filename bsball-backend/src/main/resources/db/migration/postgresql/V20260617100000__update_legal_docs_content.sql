## 三、球员身份认领

1. 若系统中存在与您相关的球员档案，您可通过自助认领或球队负责人发放的邀请链接提交认领申请。
2. 认领申请须填写真实信息；审核由球队负责人和/或平台管理员进行，我们有权拒绝虚假、重复或不符合规则的申请。
3. 认领通过后，您的账号可与对应球员档案关联，便于查看个人数据及参与相关互动；具体权限以审核结果及租户配置为准。
4. 禁止冒领他人身份、恶意重复提交或利用认领流程干扰赛事数据管理；违者我们有权拒绝申请、解除关联或限制、封禁账号。

