## 一、服务说明

1. 本系统面向棒垒球联盟、赛事组织方、球队及广大球迷，提供包括但不限于：赛事与赛程发布、比赛数据与统计排行、球队与球员档案展示、现场比赛记录、门户资讯公告、账号注册登录、球员身份认领与审核等功能。
2. 本系统可能按租户（联赛/组织）划分独立门户，不同租户展示的内容与功能以该租户管理员配置为准。
3. 我们有权根据业务需要调整、升级或暂停部分功能，并尽可能通过门户公告等方式提前告知；因系统维护、升级或不可抗力导致的服务中断，我们将在合理范围内尽力恢复，但不对因此给您造成的间接损失承担责任。

