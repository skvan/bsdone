## 二、账号注册与使用

1. **注册资格**：您应具备完全民事行为能力。若您为未成年人，应在监护人指导下阅读本协议并在取得监护人同意后使用本系统。
2. **注册方式**：您可通过手机号码及短信验证码完成注册，并设置用户名与登录密码。用户名、密码由您自行保管；因保管不善、告知他人或遭受攻击导致的账号风险与损失，由您自行承担。
3. **信息真实**：您应保证注册及后续提交的信息真实、准确、完整。我们有权对明显虚假、违法或侵犯他人权益的信息进行删除、限制或终止服务。
4. **账号安全**：您不得将账号转让、出借、出租或以其他方式供他人使用。如发现账号被盗用或存在异常，请尽快通过门户反馈或联系租户/平台管理员。
5. **会员角色**：自助注册账号默认获得「门户会员」角色，可用于浏览门户公开内容、提交球员认领申请等；**进入管理后台、编辑赛事数据等能力须由租户管理员另行授权**，会员角色本身不视为后台管理权限。

