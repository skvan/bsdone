# 隐私政策

**更新日期：2026年6月17日**  
**生效日期：2026年6月17日**

棒垒球管理系统（以下简称「本系统」或「BS-Ball」）重视您的个人信息保护。本政策说明我们如何收集、使用、存储、共享与保护您的个人信息，以及您享有的权利。**请您在使用本系统前仔细阅读；您注册或使用本系统，即表示您已理解并同意本政策。**

---

## 一、我们收集的信息

根据您使用的功能，我们可能收集以下信息：

### 1. 账号与身份信息
- **手机号码**：用于注册、登录验证、安全通知及与账号绑定的必要联系；
- **用户名、密码（加密存储）**：用于账号识别与登录；
- **昵称、头像等资料**：若您或管理员完善个人资料时填写；
- **协议同意记录**：包括您同意本政策及服务协议的时间，用于合规留痕。

### 2. 球员认领相关信息
- 认领申请中的**备注说明**、与球员档案的**关联关系**；
- 审核过程中的**审核状态、审核人、审核时间、拒绝原因**等。

### 3. 使用与设备信息
- **访问日志**：如 IP 地址、访问时间、请求路径、浏览器类型、设备类型等，用于安全审计、故障排查与统计分析；
- **门户访问统计（PV）**：用于了解页面热度，通常不直接识别个人身份；
- **Cookie 及本地存储**：用于维持登录状态、语言/主题偏好、游客反馈历史（仅存于您的浏览器）等。

### 4. 您主动提供的信息
- 通过门户**反馈**功能提交的内容及您填写的联系方式（未登录时）；
- 其他您自愿填写并提交的信息。

### 5. 我们不会主动收集的信息
- 除非为提供特定功能所必需且经您明确授权，我们不会收集您的精确地理位置、通讯录、相册等敏感权限信息。

---

## 二、我们如何使用信息

我们收集的信息将用于：

1. **提供核心服务**：账号注册与登录、短信验证码发送、球员认领与审核、门户内容展示；
2. **保障安全**：防范恶意注册、短信刷接口、未授权访问与数据篡改；
3. **改进产品**：分析功能使用情况，优化界面与性能（尽量采用汇总、匿名化方式）；
4. **履行义务**：遵守法律法规、响应有权机关依法提出的要求；
5. **与您沟通**：处理您的反馈、投诉或与服务相关的必要通知。

我们**不会**将您的个人信息出售给任何第三方。

---

## 三、信息共享与披露

我们仅在以下情形共享或披露信息：

1. **短信服务商**：为发送验证码，向依法合规的第三方短信平台提供您的手机号及短信模板所需的最少信息；
2. **租户管理员**：您所属租户的管理员、球队负责人可在其管理权限范围内查看与认领审核、球队管理相关的必要信息；
3. **法律要求**：依据法律法规、诉讼、仲裁或政府主管部门强制性要求；
4. **保护权益**：为保护本系统、用户或公众的合法权益所合理必需的情形。

---

## 四、信息存储与保护

1. **存储地点**：您的信息原则上存储在中华人民共和国境内；如需跨境传输，我们将依法履行评估、告知同意义务。
2. **存储期限**：在实现本政策所述目的所必需的期限内保留；账号注销或法定保存期届满后，我们将删除或匿名化处理。
3. **安全措施**：我们采用访问控制、传输加密（HTTPS）、密码哈希、接口限流、权限分级等合理措施保护您的信息；但互联网环境并非绝对安全，请您妥善保管账号凭证。

---

## 五、您的权利

在适用法律允许的范围内，您享有：

- **查询与更正**：登录账号后查看、修改部分个人资料；或通过反馈/contact 联系我们协助处理；
- **注销账号**：可通过联系租户或平台管理员申请注销；注销后我们将停止为您提供服务并按规定删除或匿名化相关信息；
- **撤回同意**：您可停止使用本系统；但撤回同意不影响撤回前基于同意已进行的处理；
- **投诉举报**：如认为我们的处理侵害您的合法权益，可通过本政策末尾联系方式投诉，或向有关监管部门反映。

---

## 六、未成年人保护

若您为未满 18 周岁的未成年人，请在监护人陪同下阅读本政策，并在监护人同意后使用本系统。我们不会主动面向未成年人推广不适合的内容；若发现未经监护人同意收集未成年人信息，我们将尽快删除。

---

## 七、Cookie 与本地存储

1. **登录态**：登录成功后可能在浏览器本地存储令牌，用于保持登录状态；
2. **偏好设置**：如语言、主题模式等；
3. **游客反馈**：未登录时提交的反馈记录可能保存在您本机浏览器，清除缓存后将丢失；
4. 您可通过浏览器设置管理 Cookie；禁用部分 Cookie 可能影响登录或个性化功能。

---

## 八、政策更新

我们可能适时更新本政策。重大变更将通过门户公告、注册页面或平台文档提示。更新后继续使用本系统，即视为您接受更新后的政策。

